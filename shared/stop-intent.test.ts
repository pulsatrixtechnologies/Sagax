import { describe, expect, it } from "vitest";
import { isStopIntent } from "./stop-intent";

describe("isStopIntent", () => {
  it.each([
    "stop",
    "Stop",
    "STOP!",
    "stop.",
    "  stop  ",
    "stop it",
    "Stop it!!",
    "arrête",
    "Arrête !",
    "arrete",
    "arrête ça",
    "arrete ca",
    "Annule",
    "annuler",
    "cancel",
    "Cancel…",
    "halt",
    "please stop",
    "stop please",
    "ok stop",
    "stop svp",
    "ok, arrête",
    "attends",
    "Attends!",
    "attends attends",
    "wait",
    "Wait!",
    "hold on",
    "hang on",
    "never mind",
    "laisse tomber",
    "oublie ça",
    "ça suffit",
    "arrête-toi",
    "arrêtez",
    "stop stop",
    "minute!",
    "abort",
    "pause",
    "🛑",
    "✋",
  ])("matches %j", (text) => {
    expect(isStopIntent(text)).toBe(true);
  });

  it.each([
    "",
    "   ",
    "stop the server when done",
    "can you cancel my order",
    "don't stop",
    "don't stop now please",
    "arrête de répondre en anglais",
    "arrête de faire ça",
    "never stop",
    "bus stop",
    "stop stop stop stop stop",
    "please please stop",
    "stopwatch",
    "cancel the meeting tomorrow",
    "annule la réunion",
    "attends que le build finisse",
    "wait for the tests to pass",
    "hold on to that file",
    "pause the music",
    "laisse tomber le dernier point et continue",
    "🛑 stop the server",
    "ok",
    "please",
  ])("does not match %j", (text) => {
    expect(isStopIntent(text)).toBe(false);
  });
});
