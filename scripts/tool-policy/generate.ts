// Writes server/tool-policy.generated.ts: one row per route in the inventory.
// A row already in the table keeps its reviewed fields; a new route gets the
// default classification; a row whose route is gone is dropped.
//   node scripts/tool-policy/generate.ts
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { routeInventory } from "./route-inventory.ts";
import { classifyRoute, policyKey, toolPolicyRows, type ToolPolicy } from "../../server/tool-policy.ts";

const root = fileURLToPath(new URL("../..", import.meta.url));
const existing = new Map(toolPolicyRows().map((row) => [policyKey(row), row]));
const rows: ToolPolicy[] = routeInventory(root).map(({ kind, route, method }) =>
  existing.get(policyKey({ method, kind, route })) ?? { method, kind, route, ...classifyRoute(method, route) });
const body = rows.map((row) => `  ${JSON.stringify(row)},`).join("\n");
writeFileSync(new URL("../../server/tool-policy.generated.ts", import.meta.url),
  `// Generated by scripts/tool-policy/generate.ts, then reviewed: edit a row's tier,\n// scope or defaultEnabled here; rerun the script when routes change.\nimport type { ToolPolicy } from "./tool-policy.ts";\n\nexport const TOOL_POLICY_ROWS: readonly ToolPolicy[] = [\n${body}\n];\n`);
console.log(`${rows.length} rows`);
