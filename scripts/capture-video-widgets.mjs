#!/usr/bin/env node
/**
 * Real browser screenshots of the video widget gallery (Playwright).
 * Usage: node scripts/capture-video-widgets.mjs [--out DIR]
 */
import { spawn } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outArg = process.argv.indexOf("--out");
const outDir = outArg >= 0 ? resolve(process.argv[outArg + 1]) : join(root, "docs", "screenshots", "video-widgets");

const skins = [
  { id: "pulsatrix", label: "dark" },
  { id: "daylight", label: "light" },
];

async function waitForServer(url, ms = 120_000) {
  const start = Date.now();
  while (Date.now() - start < ms) {
    try {
      const res = await fetch(url);
      if (res.status < 500) return;
    } catch {
      /* retry */
    }
    await new Promise((r) => setTimeout(r, 500));
  }
  throw new Error(`Vite gallery did not start at ${url}`);
}

const vite = spawn(
  "pnpm",
  [
    "exec",
    "vite",
    "--config",
    "vite.gallery.config.ts",
    "--host",
    "127.0.0.1",
    "--port",
    "5199",
    "--strictPort",
  ],
  { cwd: root, stdio: ["ignore", "pipe", "pipe"], env: { ...process.env, NODE_ENV: "development" } },
);

let viteLog = "";
vite.stdout?.on("data", (c) => { viteLog += c; });
vite.stderr?.on("data", (c) => { viteLog += c; });

try {
  const base = "http://127.0.0.1:5199/video-widgets.html";
  await waitForServer(base);
  const { chromium } = await import(process.env.SAGAX_VERIFY_PLAYWRIGHT || "playwright");
  await mkdir(outDir, { recursive: true });
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 920, height: 1400 } });

  for (const { id, label } of skins) {
    await page.goto(`${base}?skin=${id}`, { waitUntil: "networkidle" });
    await page.waitForSelector(".video-player-card", { timeout: 30_000 });
    await page.locator(".video-player-stage").first().hover();
    await page.waitForTimeout(1200);
    const path = join(outDir, `video-widgets-${label}.png`);
    await page.screenshot({ path, fullPage: true });
    console.log(`wrote ${path}`);
  }

  await browser.close();
  await writeFile(join(outDir, "README.txt"), "Generated by scripts/capture-video-widgets.mjs\n");
} finally {
  vite.kill("SIGTERM");
  if (vite.exitCode === null) {
    await new Promise((r) => vite.once("exit", r));
  }
  if (vite.exitCode && vite.exitCode !== 0 && !viteLog.includes("5199")) {
    console.error(viteLog);
  }
}
