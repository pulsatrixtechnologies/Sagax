// The phone's copy of the widget kit (scripts/gen-ios-widget-kit.ts writes
// ios/Sources/CompanionCore/WidgetKit.generated.swift from this): the kit's
// stylesheet as is, and the theme rule of each scheme as a template whose
// token values are placeholders the phone fills with its skin's colors
// (RichBlocks.widgetDocument). One source, so a widget draws the same on the
// desktop and on the phone. Pure.
import { contentThemeVars, cssDeclarations, fallbackWidgetTokens, WIDGET_KIT_CSS, WIDGET_THEME_TOKENS, type WidgetThemeTokens } from "./widget-kit.ts";

/** The placeholder of a token in the template: never a prefix of another. */
export function tokenPlaceholder(name: string): string {
  return `SAGAXTOKEN_${name.replace(/^--/, "").replace(/-/g, "_")}_END`;
}

const FILLED = WIDGET_THEME_TOKENS.filter((name) => name !== "--code-color-scheme");

/** The `:root` declarations of a widget in a scheme, a placeholder per token. */
export function themeTemplate(scheme: "light" | "dark"): string {
  const tokens: WidgetThemeTokens = { "--code-color-scheme": scheme };
  for (const name of FILLED) tokens[name] = tokenPlaceholder(name);
  return cssDeclarations(contentThemeVars(tokens, "chat").vars);
}

function swiftString(value: string): string {
  if (value.includes("\"###")) throw new Error("the kit holds the raw-string delimiter");
  return `###"${value}"###`;
}

function swiftDictionary(values: Record<string, string>): string {
  return `[\n${Object.entries(values).map(([key, value]) => `        ${JSON.stringify(key)}: ${swiftString(value)},`).join("\n")}\n    ]`;
}

/** The Swift file. */
export function iosWidgetKitSource(): string {
  const fallback = (scheme: "light" | "dark") => {
    const base = fallbackWidgetTokens(scheme);
    const out: Record<string, string> = {};
    for (const name of FILLED) {
      const value = base[name] ?? (name === "--identity-purple" ? base["--color-accent-text"] : undefined);
      if (value) out[name] = value;
    }
    return out;
  };
  return `// Generated by scripts/gen-ios-widget-kit.ts from src/lib/widget-kit.ts.
// Do not edit: change the web kit and run the script again.
// swiftlint:disable all

public enum WidgetKitGenerated {
    /// The app tokens a theme is written from, in order.
    public static let tokenNames: [String] = [${FILLED.map((name) => JSON.stringify(name)).join(", ")}]

    /// The kit's stylesheet: reset, typography, components.
    public static let css: String = ${swiftString(WIDGET_KIT_CSS)}

    /// The \`:root\` declarations of each scheme; each token is
    /// SAGAXTOKEN_<name>_END until the phone fills it.
    public static let darkTemplate: String = ${swiftString(themeTemplate("dark"))}
    public static let lightTemplate: String = ${swiftString(themeTemplate("light"))}

    /// The desktop's fallback skins (Midnight, Pulsatrix Light).
    public static let darkFallback: [String: String] = ${swiftDictionary(fallback("dark"))}
    public static let lightFallback: [String: String] = ${swiftDictionary(fallback("light"))}
}
`;
}
